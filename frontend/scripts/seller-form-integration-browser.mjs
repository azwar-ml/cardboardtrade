import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import Database from 'better-sqlite3';
import { chromium } from 'playwright';

const directory = process.env.TRADE_DATA_DIR;
if (!directory || !path.basename(directory).startsWith('.qa-')) throw new Error('Disposable QA database required');
const base = process.env.BASE_URL || 'http://localhost:3003';
const backend = process.env.AGENTS_API_URL || 'http://127.0.0.1:8003';
const company = 'QA Test Packaging Supplier';
const report = { checks: {}, enquiry_references: [], company, city: 'Lahore', product: 'Corrugated Boxes', email: 'qa-supplier@example.com' };
const browser = await chromium.launch({ headless: true });
try {
  const publicContext = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
  const page = await publicContext.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  publicContext.on('request', request => {
    if (/serpapi\.com|duckduckgo\.com/.test(request.url())) errors.push('Unexpected search-provider browser request');
  });
  async function submit() {
    if (await page.getByRole('button', { name: 'Send another request', exact: true }).count()) {
      await page.getByRole('button', { name: 'Send another request', exact: true }).click();
    } else {
      await page.goto(`${base}/#contact`);
    }
    await page.getByText('I want to sell', { exact: true }).click();
    await page.getByLabel('First name', { exact: true }).fill('QA');
    await page.getByLabel('Last name', { exact: true }).fill('Supplier');
    await page.getByLabel('Work email', { exact: true }).fill(report.email);
    await page.getByLabel('Company', { exact: true }).fill(company);
    await page.getByLabel('Country', { exact: true }).selectOption('Pakistan');
    await page.getByLabel('City', { exact: true }).fill(report.city);
    await page.getByLabel('Product', { exact: true }).fill(report.product);
    await page.getByLabel('What do you make?', { exact: true }).fill('Synthetic integration test only. Lahore. Corrugated Boxes. Do not contact.');
    const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/request') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Send request', exact: true }).click();
    const response = await responsePromise;
    assert.equal(response.status(), 200);
    const result = await response.json();
    assert.equal(result.ok, true);
    assert.match(result.id, /^CP-\d{6}-[A-F0-9]{10}$/);
    await page.getByRole('heading', { name: 'Request received.', exact: true }).waitFor();
    await page.getByRole('status').filter({ hasText: result.id }).waitFor();
    report.enquiry_references.push(result.id);
    return result.id;
  }
  const reference = await submit();
  report.checks['Form submission'] = 'PASS';
  const db = new Database(path.join(directory, 'trade.db'), { readonly: true });
  const first = db.prepare('SELECT * FROM discovery_leads WHERE company=?').get(company);
  assert.ok(first, 'Lead must be created by the form transaction, before opening Admin');
  assert.equal(first.city, report.city);
  assert.deepEqual(JSON.parse(first.products), [report.product]);
  assert.equal(first.email, report.email);
  const health = await (await fetch(`${backend}/health`)).json();
  const agents = await (await fetch(`${backend}/api/v1/agents`)).json();
  assert.equal(agents.agents.filter(agent => agent.mode === 'demo').length, 9);
  const expected = createHash('sha256').update(path.resolve(directory, 'trade.db').replaceAll('\\', '/').toLowerCase()).digest('hex');
  assert.equal(health.database_fingerprint, expected);

  const adminContext = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
  const admin = await adminContext.newPage();
  await admin.goto(`${base}/console/login`);
  await admin.getByLabel('Email', { exact: true }).fill('admin@qa.invalid');
  await admin.getByLabel('Password', { exact: true }).fill('qa-admin-pass');
  await admin.getByRole('button', { name: 'Sign in', exact: true }).click();
  await admin.waitForURL(/\/console$/);
  await admin.getByRole('link', { name: 'Open AI Control Center', exact: true }).click();
  await admin.locator('[data-testid="agent-card"][data-agent-id="supplier-discovery"]').click();
  const row = admin.getByRole('row').filter({ has: admin.getByRole('button', { name: company, exact: true }) });
  await row.getByText(report.city, { exact: true }).waitFor();
  await row.getByText(report.product, { exact: true }).waitFor();
  await row.getByText('Pending Review', { exact: true }).waitFor();
  report.checks['Agent #1 listing'] = 'PASS';
  await row.getByText('Website Submission', { exact: true }).waitFor();
  report.checks['Source label'] = 'PASS';
  await row.getByRole('button', { name: company, exact: true }).click();
  const details = admin.getByRole('dialog', { name: 'Supplier details' });
  await details.getByRole('heading', { name: company, exact: true }).waitFor();
  await details.getByText(report.email, { exact: false }).first().waitFor();
  await details.getByRole('link', { name: reference, exact: true }).waitFor();
  assert.ok((await details.innerText()).includes(report.city));
  assert.ok((await details.innerText()).includes(report.product));
  const sources = db.prepare('SELECT * FROM discovery_sources WHERE lead_id=?').all(first.id);
  assert.equal(sources[0].enquiry_id, reference);
  const evidence = JSON.parse(sources[0].evidence);
  assert.equal(evidence.city, report.city);
  assert.equal(evidence.product, report.product);
  assert.equal(evidence.email, report.email);
  report.checks['Enquiry reference'] = 'PASS';
  fs.mkdirSync(path.join(directory, 'screenshots'), { recursive: true });
  await admin.screenshot({ path: path.join(directory, 'screenshots/supplier-details.png'), fullPage: true });
  await admin.reload();
  await admin.getByRole('button', { name: company, exact: true }).waitFor();
  assert.equal(db.prepare('SELECT count(*) n FROM discovery_leads WHERE company=?').get(company).n, 1);
  report.checks['Data persistence'] = 'PASS';

  const secondReference = await submit();
  assert.notEqual(secondReference, reference);
  assert.equal(db.prepare('SELECT count(*) n FROM discovery_leads WHERE company=?').get(company).n, 1);
  assert.equal(db.prepare('SELECT count(*) n FROM enquiries WHERE company=?').get(company).n, 2);
  assert.equal(db.prepare('SELECT count(*) n FROM discovery_sources WHERE lead_id=?').get(first.id).n, 2);
  assert.equal(db.prepare("SELECT count(*) n FROM discovery_activity WHERE lead_id=? AND action='Duplicate linked'").get(first.id).n, 1);
  await admin.reload();
  await admin.getByRole('button', { name: company, exact: true }).click();
  await details.getByRole('link', { name: reference, exact: true }).waitFor();
  await details.getByRole('link', { name: secondReference, exact: true }).waitFor();
  assert.equal(db.prepare('SELECT status FROM discovery_leads WHERE id=?').get(first.id).status, 'Pending Review');
  report.checks['Duplicate handling'] = 'PASS';
  assert.equal(db.prepare('SELECT count(*) n FROM discovery_jobs').get().n, 0);
  assert.equal(db.prepare('SELECT count(*) n FROM discovery_search_results').get().n, 0);
  assert.equal(db.prepare("SELECT count(*) n FROM settings WHERE key LIKE 'discovery.duckduckgo.%'").get().n, 0);
  assert.equal(db.prepare('SELECT count(*) n FROM sendout_messages').get().n, 0);
  assert.equal(db.prepare('SELECT enabled FROM discovery_schedule WHERE id=1').get().enabled, 0);
  assert.deepEqual(errors, []);
  await admin.screenshot({ path: path.join(directory, 'screenshots/duplicate-references.png'), fullPage: true });
  report.provider_requests = 0;
  report.emails = 0;
  report.discovery_jobs = 0;
  report.lead_id = first.id;
  report.supplier_records = 1;
  report.submissions = 2;
  report.shared_database_identity_verified = true;
  db.close();
  fs.writeFileSync(path.join(directory, 'seller-form-results.json'), JSON.stringify(report, null, 2));
  for (const [name, result] of Object.entries(report.checks)) console.log(`${name}: ${result}`);
  console.log('Enquiry references:', report.enquiry_references.join(', '));
} finally { await browser.close(); }
