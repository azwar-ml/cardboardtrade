import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs';
import Database from 'better-sqlite3';
import { chromium } from 'playwright';
const dir = process.env.TRADE_DATA_DIR;
if (!dir || !path.basename(dir).startsWith('.qa-')) throw new Error('Disposable QA database required');
const base = process.env.BASE_URL || 'http://localhost:3001';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
const checks = [];
try {
  await page.goto(`${base}/console/login`);
  await page.getByLabel('Email').fill('admin@qa.invalid');
  await page.getByLabel('Password').fill('qa-admin-pass');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL(/\/console$/);
  const db = new Database(path.join(dir, 'trade.db'));
  const id = Number(db.prepare("INSERT INTO discovery_jobs(trigger_type,actor,status,stage,filters,created_at) VALUES('Manual','QA control fixture','Queued','Queued','{\"mode\":\"seeds\"}',?)").run(new Date().toISOString()).lastInsertRowid);
  db.close();
  await page.goto(`${base}/console/admin/agents/supplier-discovery`);
  const cancel = page.getByRole('button', { name: 'Cancel Job', exact: true });
  await cancel.waitFor();
  assert.equal(await page.getByRole('button', { name: 'Run Now', exact: true }).isDisabled(), true);
  await cancel.click();
  await page.getByRole('status').filter({ hasText: 'Job cancelled' }).waitFor();
  const getJob = await page.request.get(`${base}/api/console/discovery/jobs/${id}`);
  assert.equal((await getJob.json()).status, 'Cancelled');
  await page.reload();
  assert.equal(await page.getByRole('button', { name: 'Cancel Job', exact: true }).count(), 0);
  checks.push('PASS: Cancel Job persists and prevents queued research; Run Now disabled while active');
  const saved = await page.request.post(`${base}/api/console/discovery/schedule`, { data: { enabled: true, interval_seconds: 3600, filters: { mode: 'automatic', product: 'corrugated', city: 'Lahore', keywords: '' } } });
  assert.equal(saved.status(), 200);
  await page.reload();
  await page.getByRole('button', { name: 'Pause Automation', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Schedule paused' }).waitFor();
  await page.reload();
  const summary = await (await page.request.get(`${base}/api/console/discovery/summary`)).json();
  assert.equal(summary.schedule.enabled, false);
  assert.equal(summary.schedule.next_run_at, null);
  checks.push('PASS: Pause persists across refresh and clears next scheduled execution');
  fs.writeFileSync(path.join(dir, 'controls-browser-results.json'), JSON.stringify(checks, null, 2));
  console.log(checks.join('\n'));
} finally { await browser.close(); }
